import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";
const nativeRoot = process.env.NINHO_NATIVE_PROJECT ?? resolve(homedir(), "RiderProjects/Ninho");

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = resolve(root, "node_modules/lucide-react");
const version = JSON.parse(readFileSync(resolve(packageRoot, "package.json"), "utf8")).version;
const exportsSource = readFileSync(resolve(packageRoot, "dist/esm/lucide-react.js"), "utf8");
const exports = new Map();
for (const match of exportsSource.matchAll(/export \{([^}]+)\} from '\.\/icons\/([^']+)\.js';/g)) {
  for (const name of match[1].matchAll(/default as (\w+)/g)) exports.set(name[1], match[2]);
}
const wanted = new Set(["Clock", "Clock3", "Layers", "ChartNoAxesCombined", "Settings", "Minus"]);
const renderer = resolve(root, "src/renderer");
for (const file of readdirSync(renderer).filter((x) => /\.tsx?$/.test(x))) {
  const source = readFileSync(resolve(renderer, file), "utf8");
  for (const match of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*["']lucide-react["']/g)) {
    for (const imported of match[1].split(",").map((x) => x.trim()).filter(Boolean)) {
      wanted.add(imported.split(/\s+as\s+/)[0]);
    }
  }
}
const normalize = (name) => name.replace(/[-_\s]/g, "").toLowerCase();
const icons = new Map();
const aliases = new Map();
const number = (value) => {
  const parsed = Number(value ?? 0);
  if (!Number.isFinite(parsed)) throw new Error(`Invalid geometry number ${value}`);
  return parsed;
};
const geometry = ([kind, attr]) => {
  switch (kind) {
    case "path": {
      // XAML accepts SVG path commands. Explicit separators also handle SVG's
      // compact adjacent negatives/decimals without relying on parser quirks.
      const tokens = attr.d.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?/g);
      if (!tokens || attr.d.replace(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?|[\s,]/g, "")) {
        throw new Error(`Unsupported path ${attr.d}`);
      }
      return tokens.join(" ");
    }
    case "circle": {
      const x = number(attr.cx), y = number(attr.cy), r = number(attr.r);
      return `M ${x + r} ${y} A ${r} ${r} 0 1 0 ${x - r} ${y} A ${r} ${r} 0 1 0 ${x + r} ${y} Z`;
    }
    case "ellipse": {
      const x = number(attr.cx), y = number(attr.cy), rx = number(attr.rx), ry = number(attr.ry);
      return `M ${x + rx} ${y} A ${rx} ${ry} 0 1 0 ${x - rx} ${y} A ${rx} ${ry} 0 1 0 ${x + rx} ${y} Z`;
    }
    case "line": return `M ${number(attr.x1)} ${number(attr.y1)} L ${number(attr.x2)} ${number(attr.y2)}`;
    case "polyline":
    case "polygon": {
      const points = attr.points.trim().split(/[\s,]+/).map(number);
      if (points.length < 4 || points.length % 2) throw new Error(`Invalid ${kind}`);
      return `M ${points.slice(0, 2).join(" ")} L ${points.slice(2).join(" ")}${kind === "polygon" ? " Z" : ""}`;
    }
    case "rect": {
      const x = number(attr.x), y = number(attr.y), w = number(attr.width), h = number(attr.height);
      const rx = Math.min(w / 2, number(attr.rx ?? attr.ry)), ry = Math.min(h / 2, number(attr.ry ?? attr.rx));
      if (!rx || !ry) return `M ${x} ${y} H ${x + w} V ${y + h} H ${x} Z`;
      return `M ${x + rx} ${y} H ${x + w - rx} A ${rx} ${ry} 0 0 1 ${x + w} ${y + ry} V ${y + h - ry} A ${rx} ${ry} 0 0 1 ${x + w - rx} ${y + h} H ${x + rx} A ${rx} ${ry} 0 0 1 ${x} ${y + h - ry} V ${y + ry} A ${rx} ${ry} 0 0 1 ${x + rx} ${y} Z`;
    }
    default: throw new Error(`Unsupported Lucide primitive ${kind}`);
  }
};
for (const name of [...wanted].sort()) {
  const file = exports.get(name);
  if (!file) throw new Error(`Lucide export not found: ${name}`);
  if (!icons.has(file)) {
    const source = readFileSync(resolve(packageRoot, `dist/esm/icons/${file}.js`), "utf8");
    const match = source.match(/createLucideIcon\("([^"]+)",\s*(\[[\s\S]*\])\s*\);/);
    if (!match) throw new Error(`Unrecognized Lucide module: ${file}`);
    // This literal is local dependency source, not user-supplied input.
    const nodes = Function(`"use strict"; return (${match[2]});`)();
    icons.set(file, nodes.map(geometry));
    aliases.set(normalize(match[1]), file);
    aliases.set(normalize(file), file);
  }
  aliases.set(normalize(name), file);
}
const quoted = (value) => JSON.stringify(value);
const data = `// <auto-generated> scripts/prepare-native-icons.mjs; lucide-react ${version}. </auto-generated>
// Exact original Lucide geometry, licensed ISC; see Assets/Icons/LICENSE-LUCIDE.txt.
namespace Ninho.Windows;

internal static class OriginalIcons
{
    internal const string Version = ${quoted(version)};
    internal static readonly IReadOnlyDictionary<string, string[]> Paths = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase)
    {
${[...icons].sort(([a], [b]) => a.localeCompare(b)).map(([name, paths]) => `        [${quoted(name)}] = [${paths.map(quoted).join(", ")}],`).join("\n")}
    };
    internal static readonly IReadOnlyDictionary<string, string> Aliases = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
    {
${[...aliases].sort(([a], [b]) => a.localeCompare(b)).map(([alias, name]) => `        [${quoted(alias)}] = ${quoted(name)},`).join("\n")}
    };
}
`;
const output = resolve(nativeRoot, "Ninho.Windows/Resources/OriginalIcons.cs");
const license = resolve(nativeRoot, "Ninho.Windows/Assets/Icons/LICENSE-LUCIDE.txt");
const licenseText = readFileSync(resolve(packageRoot, "LICENSE"), "utf8");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== data || readFileSync(license, "utf8") !== licenseText) {
    throw new Error("Native icons are stale. Run node scripts/prepare-native-icons.mjs.");
  }
} else {
  mkdirSync(dirname(output), { recursive: true });
  mkdirSync(dirname(license), { recursive: true });
  writeFileSync(output, data);
  writeFileSync(license, licenseText);
}
console.log(`${process.argv.includes("--check") ? "Verified" : "Generated"} ${icons.size} native icons / ${aliases.size} aliases from lucide-react ${version}; every original renderer import is covered.`);
